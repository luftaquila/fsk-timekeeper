#!/usr/bin/env python3
"""Embed build identity, then bind the DFU package metadata to its actual bytes."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import zipfile

ROOT = Path(__file__).resolve().parents[1]
NAME = "fsk-timekeeper-metadata.json"
MARKER = b"FSK-FIRMWARE-METADATA:"


def encoded(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"))


def define(path, name):
    return int(re.search(r"^#define\s+" + name + r"\s+(\d+)u?\s*$", path.read_text(), re.M)[1])


def header(version, output):
    if not re.fullmatch(r"v?\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?", version):
        raise ValueError("Firmware version must be a semantic version")
    commit = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip()
    info = dict(schema_version=1, product="FSK-WL", board="supermini-nrf52840",
                version=version, commit=commit,
                usb_protocol=define(ROOT / "src/proto_usb.h", "PU_USB_PROTO"),
                radio_protocol=define(ROOT / "src/protocol.h", "PROTO_VER"),
                app_start=0x26000, app_limit=0xF2000)
    content = ("/* Generated by firmware_metadata.py. */\n#pragma once\n"
               f"#define FW_VERSION {json.dumps(version)}\n"
               f"#define FSK_BUILD_INFO_JSON {json.dumps(encoded(info))}\n")
    output.parent.mkdir(parents=True, exist_ok=True)
    if not output.exists() or output.read_text() != content:
        output.write_text(content)


def embedded_info(binary):
    if binary.count(MARKER) != 1:
        raise ValueError("Expected exactly one embedded firmware identity")
    return json.loads(binary.split(MARKER, 1)[1].split(b"\0", 1)[0])


def package(path, binary_path):
    binary = binary_path.read_bytes()
    info = embedded_info(binary)
    if not 8 <= len(binary) <= info["app_limit"] - info["app_start"]:
        raise ValueError("Firmware exceeds the application region")
    with zipfile.ZipFile(path) as z:
        if len(z.namelist()) != len(set(z.namelist())):
            raise ValueError("Duplicate DFU archive entries")
        entries = {n: z.read(n) for n in z.namelist() if n != NAME}
    manifest = json.loads(entries["manifest.json"])["manifest"]
    if set(manifest) != {"application", "dfu_version"} or manifest["dfu_version"] != 0.5:
        raise ValueError("Only application DFU packages are supported")
    app = manifest["application"]
    if entries[app["bin_file"]] != binary:
        raise ValueError("DFU image differs from the linked binary")
    info["files"] = {}
    for name in (app["bin_file"], app["dat_file"]):
        data = entries[name]
        info["files"][name] = dict(size=len(data), sha256=hashlib.sha256(data).hexdigest())
    metadata = (encoded(info) + "\n").encode()
    entries[NAME] = metadata
    temporary = path.with_suffix(".tmp.zip")
    with zipfile.ZipFile(temporary, "w", zipfile.ZIP_DEFLATED) as z:
        for name, data in entries.items():
            z.writestr(name, data)
    temporary.replace(path)
    path.with_name(NAME).write_bytes(metadata)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    h = commands.add_parser("header")
    h.add_argument("--version", required=True)
    h.add_argument("--output", required=True, type=Path)
    p = commands.add_parser("package")
    p.add_argument("zip", type=Path)
    p.add_argument("binary", type=Path)
    args = parser.parse_args()
    if args.command == "header":
        header(args.version, args.output)
    else:
        package(args.zip, args.binary)
